package com.example.firstmod.client.render;

import com.example.firstmod.FirstMod;
import com.mojang.blaze3d.platform.NativeImage;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.minecraft.client.Minecraft;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.texture.DynamicTexture;
import net.minecraft.client.renderer.texture.OverlayTexture;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.ClipContext;
import net.minecraft.world.level.Level;
import net.minecraft.world.phys.HitResult;
import net.minecraft.world.phys.Vec3;
import org.joml.Matrix4f;

import java.util.HashMap;
import java.util.Map;

/**
 * Projector shadow mask, sampled from a low-resolution texture.
 *
 * <p>A 48x27 mask is generated by casting rays from the lens to the screen.
 * The texture is drawn as one quad with linear filtering instead of hundreds
 * of coplanar cell quads; that avoids z-fighting/flicker and gives softer
 * shadow edges. Updates are slow (2 s) because only opaque blocks cast shadows.
 */
public final class ProjectorShadow {
	private static final int COLS = 48;
	private static final int ROWS = 27;
	private static final long UPDATE_MS = 2000L;
	private static final double RAY_OFFSET = 0.03;
	private static final double SHADOW_THRESHOLD = 0.05;
	private static final int SHADOW_ALPHA = 190;
	private static final ResourceLocation TEXTURE_ID = FirstMod.id("projector_shadow");

	private static final Map<MaskKey, Mask> CACHE = new HashMap<>();
	private static ShadowTexture texture;
	private static int raycasts;

	private ProjectorShadow() {
	}

	/** Returns the current mask, recomputing and uploading it if stale. */
	public static boolean[] mask(Level level, ProjectorOptics optics) {
		long now = System.nanoTime() / 1_000_000L;
		MaskKey key = new MaskKey(optics.projector().getBlockPos(), optics.screen().master());
		Mask cached = CACHE.get(key);
		if (cached != null && now - cached.atMs <= UPDATE_MS) {
			return cached.cells;
		}

		boolean[] cells = new boolean[COLS * ROWS];
		if (optics.brightness() <= 0.01f) {
			upload(cells);
			CACHE.put(key, new Mask(now, cells));
			return cells;
		}

		long start = System.nanoTime();
		ScreenGeometry screen = optics.screen();
		Vec3 origin = screen.surfaceOrigin();
		Vec3 right = screen.right();
		Vec3 up = screen.up();
		Vec3 lens = optics.lens();
		Vec3 normal = screen.normal();
		Vec3 sampleOrigin = origin.add(normal.scale(RAY_OFFSET));
		int blocked = 0;

		for (int row = 0; row < ROWS; row++) {
			double v = 1.0 - (row + 0.5) / ROWS;
			for (int col = 0; col < COLS; col++) {
				double u = (col + 0.5) / COLS;
				Vec3 point = sampleOrigin
					.add(right.scale(u * screen.width()))
					.add(up.scale(v * screen.height()));
				HitResult hit = level.clip(new ClipContext(lens, point,
					ClipContext.Block.COLLIDER, ClipContext.Fluid.NONE, (net.minecraft.world.entity.Entity) null));
				boolean shadowed = hit.getType() != HitResult.Type.MISS
					&& hit.getLocation().distanceToSqr(lens) < point.distanceToSqr(lens) - SHADOW_THRESHOLD;
				cells[row * COLS + col] = shadowed;
				if (shadowed) {
					blocked++;
				}
			}
		}

		double elapsedMs = (System.nanoTime() - start) / 1e6;
		raycasts++;
		if (raycasts % 20 == 1) {
			FirstMod.LOGGER.info("cinema projector: {} shadow rays, {} blocked, {} ms",
				COLS * ROWS, blocked, String.format("%.2f", elapsedMs));
		}
		if (CACHE.size() > 32) {
			CACHE.clear();
		}
		upload(cells);
		CACHE.put(key, new Mask(now, cells));
		return cells;
	}

	/** Draws the shadow mask as one translucent quad over the screen. */
	public static void render(Level level, PoseStack poseStack, MultiBufferSource bufferSource,
							  ProjectorOptics optics) {
		if (level == null) {
			return;
		}
		boolean[] cells = mask(level, optics);
		boolean any = false;
		for (boolean cell : cells) {
			if (cell) {
				any = true;
				break;
			}
		}
		if (!any) {
			return;
		}

		ScreenGeometry screen = optics.screen();
		Vec3 right = screen.right();
		Vec3 up = screen.up();
		Vec3 normal = screen.normal();
		Vec3 base = screen.localSurfaceOrigin().add(normal.scale(0.02));
		Vec3 p0 = base;
		Vec3 p1 = base.add(right.scale(screen.width()));
		Vec3 p2 = p1.add(up.scale(screen.height()));
		Vec3 p3 = base.add(up.scale(screen.height()));

		Matrix4f pose = poseStack.last().pose();
		float nx = (float) normal.x;
		float nz = (float) normal.z;
		VertexConsumer consumer = bufferSource.getBuffer(RenderType.entityTranslucent(TEXTURE_ID));
		vertex(consumer, pose, p0, 0.0f, 1.0f, nx, nz);
		vertex(consumer, pose, p1, 1.0f, 1.0f, nx, nz);
		vertex(consumer, pose, p2, 1.0f, 0.0f, nx, nz);
		vertex(consumer, pose, p3, 0.0f, 0.0f, nx, nz);
	}

	private static void upload(boolean[] cells) {
		if (Minecraft.getInstance().level == null) {
			return;
		}
		if (texture == null) {
			texture = new ShadowTexture(COLS, ROWS);
			Minecraft.getInstance().getTextureManager().register(TEXTURE_ID, texture);
		}
		NativeImage image = texture.getPixels();
		for (int row = 0; row < ROWS; row++) {
			for (int col = 0; col < COLS; col++) {
				int color = cells[row * COLS + col] ? (SHADOW_ALPHA << 24) : 0;
				image.setPixelRGBA(col, row, color);
			}
		}
		texture.upload();
	}

	private static void vertex(VertexConsumer consumer, Matrix4f pose, Vec3 point,
							   float u, float v, float nx, float nz) {
		consumer.addVertex(pose, (float) point.x, (float) point.y, (float) point.z)
			.setColor(255, 255, 255, 255)
			.setUv(u, v)
			.setOverlay(OverlayTexture.NO_OVERLAY)
			.setLight(0xF000F0)
			.setNormal(nx, 0.0f, nz);
	}

	public static void clearCache() {
		CACHE.clear();
		raycasts = 0;
	}

	private static final class ShadowTexture extends DynamicTexture {
		private ShadowTexture(int width, int height) {
			super(width, height, true);
		}

		@Override
		public void setFilter(boolean blur, boolean mipmap) {
			super.setFilter(true, false);
		}
	}

	private record MaskKey(net.minecraft.core.BlockPos projector, net.minecraft.core.BlockPos screen) {
	}

	private record Mask(long atMs, boolean[] cells) {
	}
}
